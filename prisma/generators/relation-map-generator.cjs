const { generatorHandler } = require("@prisma/generator-helper");
const { writeFileSync, mkdirSync } = require("node:fs");
const { resolve } = require("node:path");

generatorHandler({
  onManifest(config) {
    return {
      prettyName: "Relation Map Generator",
      defaultOutput: "../generated/relation-map",
      version: "1.0.0",
    };
  },

  onGenerate(options) {
    const outputDir = options.generator.output.value;
    mkdirSync(outputDir, { recursive: true });

    const lines = [];

    for (const model of options.dmmf.datamodel.models) {
      const rels = model.fields.filter(
        (f) => f.kind === "object" && f.relationName,
      );
      if (rels.length === 0) continue;

      lines.push(`  ${model.name}: [`);

      for (const f of rels) {
        lines.push(
          `    { fieldName: "${f.name}", relatedModel: "${f.type}" },`,
        );
      }

      lines.push("  ],");
    }

    const content = [
      "// Auto-generated by prisma/generators/relation-map-generator.cjs",
      "// Run `prisma generate` to regenerate.",
      "",
      "export interface RelationInfo {",
      "  fieldName: string;",
      "  relatedModel: string;",
      "}",
      "",
      "export const RELATION_MAP: Record<string, RelationInfo[]> = {",
      ...lines,
      "};",
      "",
      `export const SOFT_DELETE_MODELS = new Set([`,
      `  "Department",`,
      `  "InternProfile",`,
      `  "SupervisorProfile",`,
      `  "Issue",`,
      `  "Logbook",`,
      `  "Attendance",`,
      `  "GuidanceSession",`,
      `  "Assessment",`,
      `  "Document",`,
      `  "Guide",`,
      `]);`,
      "",
    ].join("\n");

    const modelCount = options.dmmf.datamodel.models.filter((m) =>
      m.fields.some((f) => f.kind === "object" && f.relationName),
    ).length;
    writeFileSync(resolve(outputDir, "index.ts"), content, "utf-8");
    console.log(`[relation-map] Generated relation map (${modelCount} models with relations)`);
  },
});
